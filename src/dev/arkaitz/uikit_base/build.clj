(ns dev.arkaitz.uikit-base.build
  "A host's colours, generated once and committed: `write!` from the REPL when the brand
  changes, and `expected` from the host's own test, which compares it with the committed
  file and goes red when one changed without the other. Neither runs in a running host.

  The brand is an EDN file holding one map: `{:primary \"#rrggbb\"}`, and optionally a
  `:secondary` and a `:tertiary` colour, a `:presence` (`:calm`, `:balanced`, `:vivid`) and
  an `:elevation` (`:flat`, `:normal`, `:raised`). A palette that breaks
  an audited pair, or whose status colours stop telling apart under a colour-vision
  deficiency, is refused naming what broke, and nothing is written."
  (:require [clojure.edn :as edn]
            [clojure.java.io :as io]
            [dev.arkaitz.uikit-base.audit :as audit]
            [dev.arkaitz.uikit-base.brand :as brand]
            [dev.arkaitz.uikit-base.color :as c]
            [dev.arkaitz.uikit-base.emit :as emit]))

(def ^:private colours #{:primary :secondary :tertiary})
(def ^:private levels {:presence #{:calm :balanced :vivid} :elevation #{:flat :normal :raised}})

(defn read-brand
  "The brand in the EDN file at `path`, its hexes lower-cased; refused, naming the path and
  what is wrong, unless it is readable EDN holding a map of a `:primary` colour and only the
  options the kit knows, each one of its values."
  [path]
  (let [refuse (fn [why] (throw (ex-info (str "uikit-base: " path " " why) {:path (str path)})))
        b      (try (edn/read-string (slurp (io/file path)))
                    (catch java.io.IOException _ (refuse "cannot be read"))
                    (catch RuntimeException _ (refuse "is not EDN")))]
    (when-not (map? b) (refuse "must hold one map, {:primary \"#rrggbb\"} and its options"))
    (when-not (contains? b :primary) (refuse "must name a :primary colour"))
    (when-let [unknown (seq (remove (into colours (keys levels)) (keys b)))]
      (refuse (str "names options the kit does not know: " (pr-str (vec (sort unknown))))))
    (doseq [k colours :when (contains? b k) :when (not (c/parse-hex (get b k)))]
      (refuse (str "gives " k " as no #rrggbb colour")))
    (doseq [[k allowed] levels :when (contains? b k) :when (not (allowed (get b k)))]
      (refuse (str "gives " k " as none of " (pr-str (vec (sort allowed))))))
    ;; One spelling per brand, so two equal brands write one file.
    (reduce (fn [m k] (if (contains? m k) (update m k #(.toLowerCase ^String % java.util.Locale/ROOT)) m)) b colours)))

(defn- named
  "The brand as the colours file's header names it: its primary, then each option given."
  [b]
  (str (:primary b) (apply str (for [k [:secondary :tertiary :presence :elevation] :when (contains? b k)] (str " " (name k) " " (let [v (get b k)] (if (keyword? v) (name v) v)))))))

(defn css-for
  "The colours file for a brand map, or a refusal naming every audited pair it breaks."
  [b]
  (let [tokens (brand/theme b)
        broken (audit/failures tokens)]
    (when (seq broken)
      (throw (ex-info (str "uikit-base: the palette of " (named b) " breaks " (count broken) " audited pairs: "
                           (pr-str (mapv (juxt :pair :scheme :rule) broken)))
                      {:failures broken})))
    (when-not (brand/cvd-ok?)
      (throw (ex-info "uikit-base: the status colours no longer tell apart under every colour vision" {})))
    (emit/css tokens (str "Generated by uikit-base from " (named b)
                          ". Do not edit: change the brand and regenerate (dev.arkaitz.uikit-base.build/write!)."))))

(defn expected
  "What the colours file for the brand at `brand-path` must hold."
  [brand-path]
  (css-for (read-brand brand-path)))

(defn write!
  "Generates the colours file for the brand at `brand-path` into `css-path`; answers the path."
  [brand-path css-path]
  (let [css (expected brand-path)]
    (io/make-parents (io/file css-path))
    (spit (io/file css-path) css)
    (str css-path)))
