(ns dev.arkaitz.uikit-base.build
  "A host's colours, generated once and committed: `write!` from the REPL when the brand
  changes, and `expected` from the host's own test, which compares it with the committed
  file and goes red when one changed without the other. Neither runs in a running host.

  The brand is an EDN file holding one map, `{:primary \"#rrggbb\"}`. A palette that breaks
  an audited pair, or whose status colours stop telling apart under a colour-vision
  deficiency, is refused naming what broke, and nothing is written."
  (:require [clojure.edn :as edn]
            [clojure.java.io :as io]
            [dev.arkaitz.uikit-base.audit :as audit]
            [dev.arkaitz.uikit-base.brand :as brand]
            [dev.arkaitz.uikit-base.color :as c]
            [dev.arkaitz.uikit-base.emit :as emit]))

(defn read-brand
  "The brand in the EDN file at `path`, its hex lower-cased; refused, naming the path, unless
  it is readable EDN holding exactly `{:primary \"#rrggbb\"}`."
  [path]
  (let [refuse #(throw (ex-info (str "uikit-base: " path " must hold {:primary \"#rrggbb\"} and nothing else")
                                {:path (str path)}))
        b      (try (edn/read-string (slurp (io/file path))) (catch java.io.IOException _ (refuse)) (catch RuntimeException _ (refuse)))]
    (when-not (and (map? b) (= #{:primary} (set (keys b))) (c/parse-hex (:primary b)))
      (refuse))
    ;; One spelling per brand, so two equal brands write one file.
    (update b :primary #(.toLowerCase ^String % java.util.Locale/ROOT))))

(defn css-for
  "The colours file for a brand map, or a refusal naming every audited pair it breaks."
  [b]
  (let [tokens (brand/theme b)
        broken (audit/failures tokens)]
    (when (seq broken)
      (throw (ex-info (str "uikit-base: the palette of " (:primary b) " breaks " (count broken) " audited pairs: "
                           (pr-str (mapv (juxt :pair :scheme :rule) broken)))
                      {:failures broken})))
    (when-not (brand/cvd-ok?)
      (throw (ex-info "uikit-base: the status colours no longer tell apart under every colour vision" {})))
    (emit/css tokens (str "Generated by uikit-base from " (:primary b)
                          ". Do not edit: change the brand and regenerate (dev.arkaitz.uikit-base.build/write!)."))))

(defn expected
  "What the colours file for the brand at `brand-path` must hold."
  [brand-path]
  (css-for (read-brand brand-path)))

(defn write!
  "Generates the colours file for the brand at `brand-path` into `css-path`; answers the path."
  [brand-path css-path]
  (let [css (expected brand-path)]
    (io/make-parents (io/file css-path))
    (spit (io/file css-path) css)
    (str css-path)))
